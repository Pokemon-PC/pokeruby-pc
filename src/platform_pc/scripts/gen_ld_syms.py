#!/usr/bin/env python3
"""Variables that pokeruby defines only in its linker script.

sym_ewram.txt (and sym_bss.txt) mix two kinds of lines:
    . = ALIGN(4); src/main.o(ewram_data);     -> variables defined in C
    gBattleTypeFlags = .;  . += 0x2;          -> defined *only* here
The GBA linker gives the second kind an address and a size; nothing in C
defines them. On PC they become plain globals of this generated C file
(compiled into the game data section like every game variable).

Sizes are those of the GBA (32-bit pointers). A variable that holds
pointers is larger on a 64-bit host: each one gets twice its GBA size,
aligned on 16 bytes.

Usage: gen_ld_syms.py --clang CLANG --out OUT.c --data-section SECTION
                      -- <cpp flags> sym_ewram.txt [sym_bss.txt ...]
"""
import argparse
import os
import re
import subprocess
import sys

SYM = re.compile(r'^\s*([A-Za-z_]\w*)\s*=\s*\.\s*;')
ADV = re.compile(r'^\s*\.\s*\+=\s*(0x[0-9A-Fa-f]+|\d+)\s*;')


def parse(text):
    """[(name, gba_size)] for symbols defined in the script itself."""
    out = []
    pending = None
    for raw in text.splitlines():
        for stmt in raw.split(";"):
            stmt = stmt.strip()
            if not stmt:
                continue
            m = SYM.match(stmt + ";")
            if m:
                if pending:
                    out.append((pending, 0))
                pending = m.group(1)
                continue
            m = ADV.match(stmt + ";")
            if m and pending:
                out.append((pending, int(m.group(1), 0)))
                pending = None
    if pending:
        out.append((pending, 0))
    return out


def main():
    split = sys.argv.index("--")
    ap = argparse.ArgumentParser()
    ap.add_argument("--clang", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--data-section", default="")
    a = ap.parse_args(sys.argv[1:split])
    rest = sys.argv[split + 1:]
    files = [r for r in rest if r.endswith(".txt")]
    flags = [r for r in rest if not r.endswith(".txt")]

    syms = []
    for f in files:
        r = subprocess.run([a.clang, "-E", "-P", "-x", "c"] + flags + [f], capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stderr)
            return r.returncode
        syms += parse(r.stdout)

    lines = ["/* Generated by src/platform_pc/scripts/gen_ld_syms.py - do not edit. */"]
    if a.data_section:
        lines.append('#pragma clang section data="%s"' % a.data_section)
    seen = set()
    for name, size in syms:
        if name in seen:
            continue
        seen.add(name)
        pc_size = max(2 * size, 16)
        lines.append("__attribute__((aligned(16))) unsigned char %s[%d]; /* GBA: %#x */" % (name, pc_size, size))
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    tmp = a.out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
